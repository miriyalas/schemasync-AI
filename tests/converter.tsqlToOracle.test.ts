import { describe, expect, it } from "vitest";
import { convertSql } from "@/lib/converter";

const conv = async (sql: string) => (await convertSql(sql, "sqlserver", "oracle", false)).sql;
const norm = (s: string) => s.replace(/\s+/g, " ").trim();

describe("T-SQL → Oracle: functions", () => {
  it.each([
    ["SELECT ISNULL(a, 0) FROM t", "SELECT NVL(a, 0) FROM t"],
    ["SELECT LEN(a) FROM t", "SELECT LENGTH(a) FROM t"],
    ["SELECT SUBSTRING(a, 1, 3) FROM t", "SELECT SUBSTR(a, 1, 3) FROM t"],
    ["SELECT CHARINDEX('x', a) FROM t", "SELECT INSTR(a, 'x') FROM t"],
    ["SELECT CHARINDEX('x', a, 5) FROM t", "SELECT INSTR(a, 'x', 5) FROM t"],
    ["SELECT GETDATE() FROM t", "SELECT SYSDATE FROM t"],
    ["SELECT SYSDATETIME() FROM t", "SELECT SYSTIMESTAMP FROM t"],
    ["SELECT GETUTCDATE() FROM t", "SELECT SYS_EXTRACT_UTC(SYSTIMESTAMP) FROM t"],
    ["SELECT NEWID() FROM t", "SELECT SYS_GUID() FROM t"],
    ["SELECT IIF(a > 1, 'Y', 'N') FROM t", "SELECT CASE WHEN a > 1 THEN 'Y' ELSE 'N' END FROM t"],
    ["SELECT YEAR(d), MONTH(d), DAY(d) FROM t", "SELECT EXTRACT(YEAR FROM d), EXTRACT(MONTH FROM d), EXTRACT(DAY FROM d) FROM t"],
    ["SELECT CONVERT(varchar(10), d) FROM t", "SELECT TO_CHAR(d) FROM t"],
    ["SELECT CONVERT(date, d) FROM t", "SELECT TRUNC(CAST(d AS DATE)) FROM t"],
    ["SELECT CONVERT(int, s) FROM t", "SELECT CAST(s AS NUMBER(10)) FROM t"],
  ])("%s", async (input, expected) => {
    expect(norm(await conv(input))).toBe(expected);
  });

  it.each([
    ["day", "(d + 5)"],
    ["dd", "(d + 5)"],
    ["month", "ADD_MONTHS(d, 5)"],
    ["year", "ADD_MONTHS(d, 12 * (5))"],
    ["week", "(d + 7 * (5))"],
    ["hour", "(d + (5) / 24)"],
    ["minute", "(d + (5) / 1440)"],
    ["second", "(d + (5) / 86400)"],
  ])("DATEADD(%s, 5, d)", async (part, out) => {
    expect(norm(await conv(`SELECT DATEADD(${part}, 5, d) FROM t`))).toBe(`SELECT ${out} FROM t`);
  });

  it.each([
    ["day", "(TRUNC(b) - TRUNC(a))"],
    ["month", "TRUNC(MONTHS_BETWEEN(b, a))"],
    ["year", "TRUNC(MONTHS_BETWEEN(b, a) / 12)"],
    ["hour", "ROUND((b - a) * 24)"],
  ])("DATEDIFF(%s, a, b)", async (part, out) => {
    expect(norm(await conv(`SELECT DATEDIFF(${part}, a, b) FROM t`))).toBe(`SELECT ${out} FROM t`);
  });

  it("warns and leaves unknown DATEADD parts", async () => {
    const r = await convertSql("SELECT DATEADD(quarter, 1, d) FROM t", "sqlserver", "oracle", false);
    expect(r.sql).toContain("DATEADD(quarter");
    expect(r.warnings.join()).toMatch(/DATEADD/);
  });
});

describe("T-SQL → Oracle: TOP → FETCH FIRST", () => {
  it("moves TOP to the end of the statement", async () => {
    expect(norm(await conv("SELECT TOP 5 a FROM t ORDER BY a"))).toBe("SELECT a FROM t ORDER BY a FETCH FIRST 5 ROWS ONLY");
  });
  it("handles TOP (n), DISTINCT, PERCENT and WITH TIES", async () => {
    expect(norm(await conv("SELECT DISTINCT TOP (10) a FROM t"))).toBe("SELECT DISTINCT a FROM t FETCH FIRST 10 ROWS ONLY");
    expect(norm(await conv("SELECT TOP 10 PERCENT a FROM t"))).toBe("SELECT a FROM t FETCH FIRST 10 PERCENT ROWS ONLY");
    expect(norm(await conv("SELECT TOP 3 WITH TIES a FROM t ORDER BY a"))).toBe("SELECT a FROM t ORDER BY a FETCH FIRST 3 ROWS WITH TIES");
  });
  it("does not stop at CASE … ELSE … END", async () => {
    expect(norm(await conv("SELECT TOP 5 CASE WHEN a = 1 THEN 'Y' ELSE 'N' END AS x FROM t"))).toBe(
      "SELECT CASE WHEN a = 1 THEN 'Y' ELSE 'N' END AS x FROM t FETCH FIRST 5 ROWS ONLY"
    );
  });
  it("keeps the clause inside a subquery", async () => {
    expect(norm(await conv("SELECT * FROM (SELECT TOP 1 a FROM t) x"))).toBe("SELECT * FROM (SELECT a FROM t FETCH FIRST 1 ROWS ONLY) x");
  });
  it("stops before a semicolon or the next statement", async () => {
    const out = await conv("SELECT TOP 2 a FROM t;\nSELECT b FROM u;");
    expect(norm(out)).toBe("SELECT a FROM t FETCH FIRST 2 ROWS ONLY; SELECT b FROM u;");
  });
});

describe("T-SQL → Oracle: strings, data types, syntax", () => {
  it("turns + next to string literals into ||", async () => {
    expect(norm(await conv("SELECT a + ' - ' + b FROM t"))).toBe("SELECT a || ' - ' || b FROM t");
  });
  it("leaves numeric + alone", async () => {
    expect(norm(await conv("SELECT a + 1 FROM t"))).toBe("SELECT a + 1 FROM t");
  });
  it("converts DDL data types", async () => {
    const out = norm(
      await conv(
        "CREATE TABLE x (a INT IDENTITY(1,1), b BIGINT, c SMALLINT, d TINYINT, e BIT, f DECIMAL(10,2), g NUMERIC(5), h MONEY, i NVARCHAR(50), j VARCHAR(20), k VARCHAR(MAX), l NVARCHAR(MAX), m VARBINARY(MAX), n VARBINARY(16), o UNIQUEIDENTIFIER, p DATETIME, q DATETIME2(7), r SMALLDATETIME, s FLOAT, u REAL, v DATETIMEOFFSET, w SYSNAME, y NTEXT, z SMALLMONEY)"
      )
    );
    expect(out).toBe(
      "CREATE TABLE x (a NUMBER(10) GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1), b NUMBER(19), c NUMBER(5), d NUMBER(3), e NUMBER(1), f NUMBER(10,2), g NUMBER(5), h NUMBER(19,4), i NVARCHAR2(50), j VARCHAR2(20), k CLOB, l NCLOB, m BLOB, n RAW(16), o RAW(16), p TIMESTAMP, q TIMESTAMP, r TIMESTAMP, s BINARY_DOUBLE, u BINARY_FLOAT, v TIMESTAMP WITH TIME ZONE, w NVARCHAR2(128), y NCLOB, z NUMBER(10,4))"
    );
  });
  it("does not touch words that only contain type names", async () => {
    expect(norm(await conv("SELECT Point, IntValue, a.INT FROM Bits INTO x"))).toBe("SELECT Point, IntValue, a.INT FROM Bits INTO x");
  });
  it("removes brackets, dbo., NOLOCK and SET NOCOUNT", async () => {
    expect(norm(await conv("SELECT [a] FROM [dbo].[T] WITH (NOLOCK)"))).toBe("SELECT a FROM T");
  });
  it("turns @params into :binds for plain queries", async () => {
    expect(norm(await conv("SELECT a FROM t WHERE id = @Id"))).toBe("SELECT a FROM t WHERE id = :Id");
  });
  it("adds FROM DUAL to a SELECT without FROM", async () => {
    expect(norm(await conv("SELECT GETDATE();"))).toBe("SELECT SYSDATE FROM DUAL;");
  });
  it("converts GO, PRINT, transactions and @@ROWCOUNT", async () => {
    const out = norm(await conv("BEGIN TRAN\nUPDATE t SET a = 1\nPRINT 'done'\nSELECT @@ROWCOUNT\nCOMMIT TRAN\nGO"));
    expect(out).toContain("COMMIT");
    expect(out).toContain("DBMS_OUTPUT.PUT_LINE('done')");
    expect(out).toContain("SQL%ROWCOUNT");
    expect(out).not.toMatch(/BEGIN TRAN/);
    expect(out.endsWith("/")).toBe(true);
  });
  it("never changes text inside strings or comments", async () => {
    expect(await conv("SELECT 'ISNULL(a,b) + TOP 5' AS s -- GETDATE()\nFROM t")).toBe("SELECT 'ISNULL(a,b) + TOP 5' AS s -- GETDATE()\nFROM t");
  });
});

describe("T-SQL → Oracle: procedures (rules only)", () => {
  const sp = `CREATE PROCEDURE ropa.sp_X @MinLen INT AS BEGIN SET NOCOUNT ON; BEGIN TRY SELECT TOP 10 a FROM t WHERE LEN(a) > @MinLen; END TRY BEGIN CATCH THROW; END CATCH END;`;
  it("marks procedural code, keeps @params and gives Low confidence", async () => {
    const r = await convertSql(sp, "sqlserver", "oracle", false);
    expect(r.procedural).toBe(true);
    expect(r.confidence).toBe("Low");
    expect(r.sql).toContain("CREATE OR REPLACE PROCEDURE");
    expect(r.sql).toContain("@MinLen");
    expect(r.sql).toContain("FETCH FIRST 10 ROWS ONLY;");
    expect(r.warnings[0]).toMatch(/Procedural code detected/);
  });
  it("warns about temp tables and SCOPE_IDENTITY", async () => {
    const r = await convertSql("CREATE PROCEDURE p AS SELECT * INTO #x FROM t; SELECT SCOPE_IDENTITY();", "sqlserver", "oracle", false);
    expect(r.warnings.join(" ")).toMatch(/Temp tables/);
    expect(r.warnings.join(" ")).toMatch(/SCOPE_IDENTITY/);
  });
});
