import { describe, expect, it } from "vitest";
import { convertSql } from "@/lib/converter";

const conv = async (sql: string) => (await convertSql(sql, "oracle", "sqlserver", false)).sql;
const norm = (s: string) => s.replace(/\s+/g, " ").trim();

describe("Oracle → T-SQL: functions", () => {
  it.each([
    ["SELECT NVL(a, 0) FROM t", "SELECT ISNULL(a, 0) FROM t"],
    ["SELECT NVL2(a, 1, 0) FROM t", "SELECT CASE WHEN a IS NOT NULL THEN 1 ELSE 0 END FROM t"],
    ["SELECT LENGTH(a) FROM t", "SELECT LEN(a) FROM t"],
    ["SELECT SUBSTR(a, 2, 3) FROM t", "SELECT SUBSTRING(a, 2, 3) FROM t"],
    ["SELECT SUBSTR(a, 2) FROM t", "SELECT SUBSTRING(a, 2, LEN(a)) FROM t"],
    ["SELECT INSTR(a, 'x') FROM t", "SELECT CHARINDEX('x', a) FROM t"],
    ["SELECT SYSDATE FROM t", "SELECT GETDATE() FROM t"],
    ["SELECT SYSTIMESTAMP FROM t", "SELECT SYSDATETIME() FROM t"],
    ["SELECT SYS_GUID() FROM t", "SELECT NEWID() FROM t"],
    ["SELECT ADD_MONTHS(d, 3) FROM t", "SELECT DATEADD(month, 3, d) FROM t"],
    ["SELECT TO_CHAR(n) FROM t", "SELECT CAST(n AS NVARCHAR(4000)) FROM t"],
    ["SELECT TO_NUMBER(s) FROM t", "SELECT CAST(s AS DECIMAL(38,10)) FROM t"],
    ["SELECT EXTRACT(YEAR FROM d) FROM t", "SELECT DATEPART(year, d) FROM t"],
    ["SELECT DECODE(a, 1, 'one', 2, 'two', 'other') FROM t", "SELECT CASE a WHEN 1 THEN 'one' WHEN 2 THEN 'two' ELSE 'other' END FROM t"],
    ["SELECT DECODE(a, 1, 'one') FROM t", "SELECT CASE a WHEN 1 THEN 'one' END FROM t"],
    ["SELECT s.NEXTVAL FROM t", "SELECT NEXT VALUE FOR s FROM t"],
  ])("%s", async (input, expected) => {
    expect(norm(await conv(input))).toBe(expected);
  });

  it("warns on format masks and fractional month logic", async () => {
    const r = await convertSql("SELECT TO_CHAR(d, 'YYYY'), TO_DATE(s, 'YYYY-MM-DD'), MONTHS_BETWEEN(a, b), TRUNC(d) FROM t", "oracle", "sqlserver", false);
    expect(norm(r.sql)).toBe("SELECT FORMAT(d, 'YYYY'), CONVERT(DATETIME2, s), DATEDIFF(month, b, a), CAST(d AS DATE) FROM t");
    expect(r.warnings.length).toBeGreaterThanOrEqual(4);
  });

  it("leaves INSTR with an occurrence argument and warns", async () => {
    const r = await convertSql("SELECT INSTR(a, 'x', 1, 2) FROM t", "oracle", "sqlserver", false);
    expect(r.sql).toContain("INSTR(a, 'x', 1, 2)");
    expect(r.warnings.join()).toMatch(/occurrence/);
  });
});

describe("Oracle → T-SQL: FETCH FIRST → TOP", () => {
  it("moves FETCH FIRST to SELECT TOP", async () => {
    expect(norm(await conv("SELECT a FROM t ORDER BY a FETCH FIRST 5 ROWS ONLY"))).toBe("SELECT TOP (5) a FROM t ORDER BY a");
  });
  it("handles DISTINCT, NEXT, PERCENT and WITH TIES", async () => {
    expect(norm(await conv("SELECT DISTINCT a FROM t FETCH NEXT 1 ROW ONLY"))).toBe("SELECT DISTINCT TOP (1) a FROM t");
    expect(norm(await conv("SELECT a FROM t ORDER BY a FETCH FIRST 10 PERCENT ROWS WITH TIES"))).toBe("SELECT TOP (10) PERCENT WITH TIES a FROM t ORDER BY a");
  });
  it("keeps OFFSET … FETCH (supported by SQL Server)", async () => {
    expect(norm(await conv("SELECT a FROM t ORDER BY a OFFSET 10 ROWS FETCH NEXT 5 ROWS ONLY"))).toBe("SELECT a FROM t ORDER BY a OFFSET 10 ROWS FETCH NEXT 5 ROWS ONLY");
  });
  it("targets the right SELECT in subqueries", async () => {
    expect(norm(await conv("SELECT * FROM (SELECT a FROM t FETCH FIRST 1 ROWS ONLY) x"))).toBe("SELECT * FROM (SELECT TOP (1) a FROM t) x");
  });
});

describe("Oracle → T-SQL: strings, types, syntax", () => {
  it("converts || to + with a NULL warning", async () => {
    const r = await convertSql("SELECT a || ' ' || b FROM t", "oracle", "sqlserver", false);
    expect(norm(r.sql)).toBe("SELECT a + ' ' + b FROM t");
    expect(r.warnings.join()).toMatch(/NULL/);
  });
  it("removes FROM DUAL and converts bind variables", async () => {
    expect(norm(await conv("SELECT :x FROM DUAL"))).toBe("SELECT @x");
  });
  it("does not treat := assignment as a bind variable (procedural)", async () => {
    const r = await convertSql("BEGIN v_a := 1; END;", "oracle", "sqlserver", false);
    expect(r.sql).toContain(":=");
    expect(r.procedural).toBe(true);
  });
  it("converts DDL data types", async () => {
    const out = norm(
      await conv(
        'CREATE TABLE "X" (a NUMBER(10) GENERATED BY DEFAULT AS IDENTITY (START WITH 100 INCREMENT BY 5), b NUMBER(19), c NUMBER(5), d NUMBER(3), e NUMBER(1), f NUMBER(10,2), g NUMBER(25), h NUMBER, i VARCHAR2(50 CHAR), j NVARCHAR2(20), k CLOB, l NCLOB, m BLOB, n RAW(16), o RAW(8), p TIMESTAMP(6), q TIMESTAMP WITH TIME ZONE, r BINARY_DOUBLE, s BINARY_FLOAT, u NUMBER(*,0))'
      )
    );
    expect(out).toBe(
      "CREATE TABLE X (a INT IDENTITY(100,5), b BIGINT, c SMALLINT, d TINYINT, e BIT, f DECIMAL(10,2), g DECIMAL(25,0), h DECIMAL(38,10), i VARCHAR(50), j NVARCHAR(20), k VARCHAR(MAX), l NVARCHAR(MAX), m VARBINARY(MAX), n UNIQUEIDENTIFIER, o VARBINARY(8), p DATETIME2, q DATETIMEOFFSET, r FLOAT, s REAL, u DECIMAL(38,0))"
    );
  });
  it("converts DATE and TIMESTAMP literals", async () => {
    expect(norm(await conv("SELECT a FROM t WHERE d > DATE '2024-01-01' AND e < TIMESTAMP '2024-01-01 10:00:00'"))).toBe(
      "SELECT a FROM t WHERE d > CAST('2024-01-01' AS DATE) AND e < CAST('2024-01-01 10:00:00' AS DATETIME2)"
    );
  });
  it("converts CREATE OR REPLACE, / and DBMS_OUTPUT", async () => {
    const out = await conv("CREATE OR REPLACE VIEW v AS SELECT 1 x FROM DUAL;\n/");
    expect(out).toBe("CREATE OR ALTER VIEW v AS SELECT 1 x;\nGO");
    const p = await conv("BEGIN DBMS_OUTPUT.PUT_LINE('hi'); END;");
    expect(p).toContain("PRINT 'hi';");
  });
  it.each([
    ["SELECT a FROM t WHERE ROWNUM <= 5", /ROWNUM/],
    ["SELECT a FROM t START WITH p IS NULL CONNECT BY PRIOR id = p", /CONNECT BY/],
    ["SELECT a FROM t, u WHERE t.id = u.id(+)", /\(\+\)/],
    ["SELECT a FROM t WHERE d > DATE '2024-01-01'", /DATE also stores the time/],
  ])("warns on %s", async (sql, re) => {
    const r = await convertSql(sql, "oracle", "sqlserver", false);
    expect(r.warnings.join(" ")).toMatch(re);
  });
});
